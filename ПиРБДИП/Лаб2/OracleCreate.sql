-- 1. Таблица: Vendors (Поставщики)
CREATE TABLE Vendors (
    Vendor_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name        NVARCHAR2(255) NOT NULL,
    Email       NVARCHAR2(255)
);

-- 2. Таблица: Locations (Помещения)
CREATE TABLE Locations (
    Location_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Room_Number          NVARCHAR2(50) NOT NULL,
    Planned_Growth_Seats NUMBER DEFAULT 0
);

-- 3. Таблица: Products (Репозиторий ПО)
CREATE TABLE Products (
    Product_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Vendor_ID   NUMBER NOT NULL,
    Name        NVARCHAR2(255) NOT NULL,
    Category    NVARCHAR2(100) NOT NULL,
    Version     NVARCHAR2(50),
    CONSTRAINT fk_products_vendors FOREIGN KEY (Vendor_ID) REFERENCES Vendors(Vendor_ID)
);

-- 4. Таблица: Licenses (Лицензии)
CREATE TABLE Licenses (
    License_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Product_ID       NUMBER NOT NULL,
    Purchase_Date    DATE NOT NULL,
    Expiration_Date  DATE,
    Unit_Price       NUMBER(18, 2) NOT NULL,
    Total_Seats      NUMBER NOT NULL,
    CONSTRAINT fk_licenses_products FOREIGN KEY (Product_ID) REFERENCES Products(Product_ID)
);

-- 5. Таблица: Devices (Инвентаризация оборудования)
CREATE TABLE Devices (
    Device_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Location_ID          NUMBER NOT NULL,
    Device_Type          NVARCHAR2(50) NOT NULL,
    Purchase_Date        DATE NOT NULL,
    Service_Life_Months  NUMBER NOT NULL,
    Hostname             NVARCHAR2(100),
    CONSTRAINT fk_devices_locations FOREIGN KEY (Location_ID) REFERENCES Locations(Location_ID)
);

-- 6. Таблица: Installations (Учет использования)
CREATE TABLE Installations (
    Install_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Device_ID           NUMBER NOT NULL,
    License_ID          NUMBER NOT NULL,
    Last_Activity_Date  TIMESTAMP,
    Usage_Count         NUMBER DEFAULT 0,
    CONSTRAINT fk_inst_devices FOREIGN KEY (Device_ID) REFERENCES Devices(Device_ID),
    CONSTRAINT fk_inst_licenses FOREIGN KEY (License_ID) REFERENCES Licenses(License_ID)
);

-- 7. Таблица: Requests (Заявки)
CREATE TABLE Requests (
    Request_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Product_ID    NUMBER NOT NULL,
    User_Name     NVARCHAR2(255) NOT NULL,
    User_Email    NVARCHAR2(255),
    Request_Date  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Status        NVARCHAR2(50) DEFAULT 'В ожидании',
    CONSTRAINT fk_requests_products FOREIGN KEY (Product_ID) REFERENCES Products(Product_ID)
);


CREATE OR REPLACE VIEW vw_ProductCostSummary AS
SELECT 
    p.Product_ID,
    p.Name AS ProductName,
    EXTRACT(YEAR FROM l.Purchase_Date) AS Year,
    EXTRACT(MONTH FROM l.Purchase_Date) AS Month,
    SUM(l.Total_Seats) AS TotalQuantity,
    SUM(l.Total_Seats * l.Unit_Price) AS TotalCost
FROM Licenses l
JOIN Products p ON l.Product_ID = p.Product_ID
GROUP BY p.Product_ID, p.Name, EXTRACT(YEAR FROM l.Purchase_Date), EXTRACT(MONTH FROM l.Purchase_Date);
/

CREATE OR REPLACE VIEW vw_VendorSpending AS
SELECT 
    v.Vendor_ID,
    v.Name AS VendorName,
    EXTRACT(YEAR FROM l.Purchase_Date) AS Year,
    EXTRACT(MONTH FROM l.Purchase_Date) AS Month,
    SUM(l.Total_Seats * l.Unit_Price) AS TotalSpent
FROM Licenses l
JOIN Products p ON l.Product_ID = p.Product_ID
JOIN Vendors v ON p.Vendor_ID = v.Vendor_ID
WHERE l.Purchase_Date >= ADD_MONTHS(SYSDATE, -6)
GROUP BY v.Vendor_ID, v.Name, EXTRACT(YEAR FROM l.Purchase_Date), EXTRACT(MONTH FROM l.Purchase_Date);
/

