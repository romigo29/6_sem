CREATE OR REPLACE PROCEDURE sp_AddVendor(
    p_Name IN VARCHAR2,
    p_Email IN VARCHAR2 DEFAULT NULL
) IS
BEGIN
    INSERT INTO Vendors (Name, Email)
    VALUES (p_Name, p_Email);
END;
/

CREATE OR REPLACE PROCEDURE sp_AddLocation(
    p_Room_Number IN VARCHAR2,
    p_Planned_Growth_Seats IN NUMBER DEFAULT 0
) IS
BEGIN
    INSERT INTO Locations (Room_Number, Planned_Growth_Seats)
    VALUES (p_Room_Number, p_Planned_Growth_Seats);
END;
/

CREATE OR REPLACE PROCEDURE sp_AddProduct(
    p_Vendor_ID IN NUMBER,
    p_Name IN VARCHAR2,
    p_Category IN VARCHAR2,
    p_Version IN VARCHAR2 DEFAULT NULL
) IS
BEGIN
    INSERT INTO Products (Vendor_ID, Name, Category, Version)
    VALUES (p_Vendor_ID, p_Name, p_Category, p_Version);
END;
/

CREATE OR REPLACE PROCEDURE sp_AddLicense(
    p_Product_ID IN NUMBER,
    p_Purchase_Date IN DATE,
    p_Expiration_Date IN DATE DEFAULT NULL,
    p_Unit_Price IN NUMBER,
    p_Total_Seats IN NUMBER
) IS
BEGIN
    INSERT INTO Licenses (Product_ID, Purchase_Date, Expiration_Date, Unit_Price, Total_Seats)
    VALUES (p_Product_ID, p_Purchase_Date, p_Expiration_Date, p_Unit_Price, p_Total_Seats);
END;
/

CREATE OR REPLACE PROCEDURE sp_AddDevice(
    p_Location_ID IN NUMBER,
    p_Device_Type IN VARCHAR2,
    p_Purchase_Date IN DATE,
    p_Service_Life_Months IN NUMBER,
    p_Hostname IN VARCHAR2 DEFAULT NULL
) IS
BEGIN
    INSERT INTO Devices (Location_ID, Device_Type, Purchase_Date, Service_Life_Months, Hostname)
    VALUES (p_Location_ID, p_Device_Type, p_Purchase_Date, p_Service_Life_Months, p_Hostname);
END;
/

CREATE OR REPLACE PROCEDURE sp_AddInstallation(
    p_Device_ID IN NUMBER,
    p_License_ID IN NUMBER,
    p_Last_Activity_Date IN DATE DEFAULT NULL,
    p_Usage_Count IN NUMBER DEFAULT 0
) IS
BEGIN
    INSERT INTO Installations (Device_ID, License_ID, Last_Activity_Date, Usage_Count)
    VALUES (p_Device_ID, p_License_ID, p_Last_Activity_Date, p_Usage_Count);
END;
/

CREATE OR REPLACE PROCEDURE sp_AddRequest(
    p_Product_ID IN NUMBER,
    p_User_Name IN VARCHAR2,
    p_User_Email IN VARCHAR2 DEFAULT NULL,
    p_Request_Date IN DATE DEFAULT SYSDATE,
    p_Status IN VARCHAR2 DEFAULT 'В ожидании'
) IS
BEGIN
    INSERT INTO Requests (Product_ID, User_Name, User_Email, Request_Date, Status)
    VALUES (p_Product_ID, p_User_Name, p_User_Email, p_Request_Date, p_Status);
END;
/

-- Продукты по поставщику
CREATE OR REPLACE FUNCTION fn_GetProductsByVendor(p_Vendor_ID IN NUMBER)
RETURN SYS_REFCURSOR IS
    rc SYS_REFCURSOR;
BEGIN
    OPEN rc FOR
        SELECT Product_ID, Name, Category, Version
        FROM Products
        WHERE Vendor_ID = p_Vendor_ID;
    RETURN rc;
END;
/

-- Лицензии по продукту
CREATE OR REPLACE FUNCTION fn_GetLicensesByProduct(p_Product_ID IN NUMBER)
RETURN SYS_REFCURSOR IS
    rc SYS_REFCURSOR;
BEGIN
    OPEN rc FOR
        SELECT License_ID, Product_ID, Purchase_Date, Expiration_Date, Unit_Price, Total_Seats
        FROM Licenses
        WHERE Product_ID = p_Product_ID;
    RETURN rc;
END;
/

-- Устройства по локации
CREATE OR REPLACE FUNCTION fn_GetDevicesByLocation(p_Location_ID IN NUMBER)
RETURN SYS_REFCURSOR IS
    rc SYS_REFCURSOR;
BEGIN
    OPEN rc FOR
        SELECT Device_ID, Device_Type, Purchase_Date, Service_Life_Months, Hostname
        FROM Devices
        WHERE Location_ID = p_Location_ID;
    RETURN rc;
END;
/

-- Установки по устройству
CREATE OR REPLACE FUNCTION fn_GetInstallationsByDevice(p_Device_ID IN NUMBER)
RETURN SYS_REFCURSOR IS
    rc SYS_REFCURSOR;
BEGIN
    OPEN rc FOR
        SELECT Install_ID, License_ID, Last_Activity_Date, Usage_Count
        FROM Installations
        WHERE Device_ID = p_Device_ID;
    RETURN rc;
END;
/

-- Запросы по продукту
CREATE OR REPLACE FUNCTION fn_GetRequestsByProduct(p_Product_ID IN NUMBER)
RETURN SYS_REFCURSOR IS
    rc SYS_REFCURSOR;
BEGIN
    OPEN rc FOR
        SELECT Request_ID, User_Name, User_Email, Request_Date, Status
        FROM Requests
        WHERE Product_ID = p_Product_ID;
    RETURN rc;
END;
/

-- Получить поставщика
CREATE OR REPLACE FUNCTION fn_GetVendor(p_Vendor_ID IN NUMBER)
RETURN SYS_REFCURSOR IS
    rc SYS_REFCURSOR;
BEGIN
    OPEN rc FOR
        SELECT Vendor_ID, Name, Email
        FROM Vendors
        WHERE Vendor_ID = p_Vendor_ID;
    RETURN rc;
END;
/

-- Активные лицензии
CREATE OR REPLACE FUNCTION fn_GetActiveLicenses
RETURN SYS_REFCURSOR IS
    rc SYS_REFCURSOR;
BEGIN
    OPEN rc FOR
        SELECT License_ID, Product_ID, Purchase_Date, Expiration_Date, Unit_Price, Total_Seats
        FROM Licenses
        WHERE Expiration_Date IS NULL OR Expiration_Date >= SYSDATE;
    RETURN rc;
END;
