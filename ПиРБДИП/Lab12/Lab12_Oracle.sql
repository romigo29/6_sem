CREATE OR REPLACE PROCEDURE sp_GetXmlReportByVendorName
(
    p_vendor_name IN NVARCHAR2,
    p_result OUT SYS_REFCURSOR
)
AS
BEGIN
    OPEN p_result FOR
        SELECT
            r.id AS report_id,
            x.vendor_id,
            x.vendor_name,
            x.product_id,
            x.product_name,
            x.category,
            x.license_id,
            x.unit_price,
            x.total_seats,
            x.license_cost
        FROM Report r
            CROSS JOIN XMLTABLE(
                '/LicenseReport/Licenses/LicenseInfo[@vendorName=$vendorName]'
                PASSING r.report_xml, p_vendor_name AS "vendorName"
                COLUMNS
                    vendor_id NUMBER PATH '@vendorId',
                    vendor_name NVARCHAR2(255) PATH '@vendorName',
                    product_id NUMBER PATH '@productId',
                    product_name NVARCHAR2(255) PATH '@productName',
                    category NVARCHAR2(100) PATH '@category',
                    license_id NUMBER PATH '@licenseId',
                    unit_price NUMBER(18,2) PATH 'UnitPrice',
                    total_seats NUMBER PATH 'TotalSeats',
                    license_cost NUMBER(18,2) PATH 'LicenseCost'
            ) x;
END;
/


VARIABLE rc REFCURSOR;
BEGIN
    sp_GetXmlReportByVendorName('Microsoft', :rc);
END;
