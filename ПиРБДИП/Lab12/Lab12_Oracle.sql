CREATE OR REPLACE PROCEDURE sp_InsertLicenseReport
AS
    v_xml XMLTYPE;
    v_id  NUMBER;
BEGIN
    sp_GenerateLicenseXml(v_xml);

    INSERT INTO Report(report_xml)
    VALUES (v_xml)
    RETURNING id INTO v_id;

    COMMIT;
END;
