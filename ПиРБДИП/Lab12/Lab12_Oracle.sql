-- 2. Процедура генерации XML

CREATE OR REPLACE PROCEDURE sp_GenerateLicenseXml
(
    p_report_xml OUT XMLTYPE
)
AS
BEGIN
    SELECT XMLELEMENT(
               "LicenseReport",
               XMLATTRIBUTES(
                   TO_CHAR(SYSTIMESTAMP, 'YYYY-MM-DD"T"HH24:MI:SS.FF3') AS "generatedAt"
    ),
    (
    SELECT XMLELEMENT(
        "Total",
        XMLELEMENT("LicensesCount", COUNT(*)),
        XMLELEMENT("TotalSeats", SUM(l.Total_Seats)),
        XMLELEMENT("TotalCost", SUM(l.Unit_Price * l.Total_Seats))
        )
    FROM Licenses l
    ),

    XMLELEMENT(
        "Licenses",
            (
                SELECT XMLAGG(
                    XMLELEMENT(
                        "LicenseInfo",
                                      XMLATTRIBUTES(
                                          v.Vendor_ID  AS "vendorId",
                                          v.Name AS "vendorName",
                                          p.Product_ID AS "productId",
                                          p.Name AS "productName",
                                          p.Category AS "category",
                                          l.License_ID AS "licenseId"
                                      ),
                                      XMLELEMENT("UnitPrice", l.Unit_Price),
                                      XMLELEMENT("TotalSeats", l.Total_Seats),
                                      XMLELEMENT("LicenseCost", l.Unit_Price * l.Total_Seats)
                                  )
                                  ORDER BY v.Vendor_ID, p.Product_ID, l.License_ID
                              )
                       FROM Vendors v
                           JOIN Products p ON p.Vendor_ID = v.Vendor_ID
                           JOIN Licenses l ON l.Product_ID = p.Product_ID
                   )
               ),
               XMLELEMENT(
                   "VendorTotals",
                   (
                       SELECT XMLAGG(
                                  XMLELEMENT(
                                      "VendorTotal",
                                      XMLATTRIBUTES(t.vendor_name AS "vendorName"),
                                      XMLELEMENT("LicensesCount", t.licenses_count),
                                      XMLELEMENT("TotalSeats", t.total_seats),
                                      XMLELEMENT("VendorTotalCost", t.vendor_total_cost)
                                  )
                                  ORDER BY t.vendor_name
                              )
                       FROM
                       (
                           SELECT
                               v.Name AS vendor_name,
                               COUNT(l.License_ID) AS licenses_count,
                               SUM(l.Total_Seats) AS total_seats,
                               SUM(l.Unit_Price * l.Total_Seats) AS vendor_total_cost
                           FROM Vendors v
                               JOIN Products p ON p.Vendor_ID = v.Vendor_ID
                               JOIN Licenses l ON l.Product_ID = p.Product_ID
                           GROUP BY v.Name
                       ) t
                   )
               )
           )
    INTO p_report_xml
    FROM dual;
END;
/

