-- 2. Процедура GetProductHierarchy

CREATE OR REPLACE PROCEDURE GetProductHierarchy (
    p_ParentID IN NUMBER   -- Product_ID родительского узла
)
AS
BEGIN
    FOR rec IN (
        SELECT Product_ID,
               Name,
               Category,
               Parent_ID,
               LEVEL AS Hierarchy_Level,
               SYS_CONNECT_BY_PATH(Name, ' / ') AS Full_Path
        FROM   Products
        START WITH Product_ID = p_ParentID
        CONNECT BY PRIOR Product_ID = Parent_ID
        ORDER SIBLINGS BY Name
    )
    LOOP
        DBMS_OUTPUT.PUT_LINE(
            LPAD(' ', (rec.Hierarchy_Level - 1) * 4) ||
            'ID='       || rec.Product_ID      ||
            ' Name='    || rec.Name            ||
            ' Cat='     || rec.Category        ||
            ' Parent='  || NVL(TO_CHAR(rec.Parent_ID), 'NULL') ||
            ' Level='   || rec.Hierarchy_Level ||
            ' Path='    || rec.Full_Path
        );
    END LOOP;
END;
/


-- 3. Процедура AddProductChild

CREATE OR REPLACE PROCEDURE AddProductChild (
    p_ParentID  IN NUMBER,
    p_Vendor_ID IN NUMBER,
    p_Name      IN VARCHAR2,
    p_Category  IN VARCHAR2,
    p_Version   IN VARCHAR2
)
AS
    v_exists NUMBER;
BEGIN
    -- Проверяем, что родитель существует
    SELECT COUNT(*)
    INTO   v_exists
    FROM   Products
    WHERE  Product_ID = p_ParentID;

    IF v_exists = 0 THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Родительский узел с Product_ID=' || p_ParentID || ' не найден');
    END IF;

    INSERT INTO Products (Vendor_ID, Name, Category, Version, Parent_ID)
    VALUES (p_Vendor_ID, p_Name, p_Category, p_Version, p_ParentID);

    COMMIT;
END;
/


-- 4. Процедура MoveProductSubtree

CREATE OR REPLACE PROCEDURE MoveProductSubtree (
    p_NodeID      IN NUMBER,   -- Product_ID перемещаемого узла
    p_NewParentID IN NUMBER    -- Product_ID нового родителя
)
AS
    v_exists    NUMBER;
    v_is_cycle  NUMBER;
BEGIN
    -- Проверяем, что новый родитель существует
    SELECT COUNT(*)
    INTO   v_exists
    FROM   Products
    WHERE  Product_ID = p_NewParentID;

    IF v_exists = 0 THEN
        RAISE_APPLICATION_ERROR(-20002,
            'Новый родитель с Product_ID=' || p_NewParentID || ' не найден');
    END IF;

    SELECT COUNT(*)
    INTO   v_is_cycle
    FROM   Products
    WHERE  Product_ID = p_NewParentID
    START WITH Product_ID = p_NodeID
    CONNECT BY PRIOR Product_ID = Parent_ID;

    IF v_is_cycle > 0 THEN
        RAISE_APPLICATION_ERROR(-20003,
            'Нельзя переместить узел под собственного потомка — образуется цикл');
    END IF;

    -- Переносим: достаточно обновить одну строку
    UPDATE Products
    SET    Parent_ID = p_NewParentID
    WHERE  Product_ID = p_NodeID;

    COMMIT;
END;
/


