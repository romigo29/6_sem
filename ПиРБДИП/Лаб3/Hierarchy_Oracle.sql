-- Просмотр иерархии через CONNECT BY (без процедуры, для наглядности)
SELECT Product_ID,
       LPAD(' ', (LEVEL - 1) * 4) || Name AS Tree_View,
       Category,
       Parent_ID,
       LEVEL AS Hierarchy_Level,
       SYS_CONNECT_BY_PATH(Name, ' / ') AS Full_Path
FROM   Products
START WITH Parent_ID IS NULL
CONNECT BY PRIOR Product_ID = Parent_ID
ORDER SIBLINGS BY Name;


-- То же через рекурсивный CTE (альтернатива CONNECT BY)
WITH hierarchy (Product_ID, Name, Category, Parent_ID, Lvl, Full_Path) AS (
    -- Якорь: корневые узлы
    SELECT Product_ID, Name, Category, Parent_ID,
           1 AS Lvl,
           '/ ' || Name AS Full_Path
    FROM   Products
    WHERE  Parent_ID IS NULL

    UNION ALL

    -- Рекурсивный шаг: дети
    SELECT p.Product_ID, p.Name, p.Category, p.Parent_ID,
           h.Lvl + 1,
           h.Full_Path || ' / ' || p.Name
    FROM   Products p
    JOIN   hierarchy h ON p.Parent_ID = h.Product_ID
)
SELECT Product_ID,
       LPAD(' ', (Lvl - 1) * 4) || Name AS Tree_View,
       Category,
       Parent_ID,
       Lvl AS Hierarchy_Level,
       Full_Path
FROM   hierarchy
ORDER  BY Full_Path;


