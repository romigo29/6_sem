-- Какой тип ПО (категория) использовался
-- наибольшее число раз для устройств определённого вида
-- Одним запросом, без процедуры
WITH cte AS (
    SELECT
    d.Device_Type AS Device_Type,
    p.Category AS Category,
    COUNT(*) AS Install_Count,
    ROW_NUMBER() OVER (
        PARTITION BY d.Device_Type
        ORDER BY COUNT(*) DESC
    ) AS rn
FROM Installations i
    JOIN Devices  d ON i.Device_ID  = d.Device_ID
    JOIN Licenses l ON i.License_ID = l.License_ID
    JOIN Products p ON l.Product_ID = p.Product_ID
GROUP BY d.Device_Type, p.Category
)

SELECT Device_Type, Category, Install_Count
FROM cte
WHERE rn = 1;
