-- 3
-- Вычисление итогов стоимости определенного вида ПО
-- помесячно, за квартал, за полгода, за год
-- Одним запросом, без процедуры
WITH src AS (
    SELECT
        p.Name AS ProductName,
        EXTRACT(YEAR FROM l.Purchase_Date) AS Yr,
        EXTRACT(MONTH FROM l.Purchase_Date) AS Mn,
        TO_NUMBER(TO_CHAR(l.Purchase_Date, 'Q')) AS Qr,
        CASE
            WHEN EXTRACT(MONTH FROM l.Purchase_Date) <= 6 THEN 1
            ELSE 2
        END AS Hf,
        l.Total_Seats AS TotalSeats,
        l.Unit_Price AS UnitPrice
    FROM Licenses l
    JOIN Products p
        ON p.Product_ID = l.Product_ID
    WHERE l.Product_ID = 2
      AND l.Purchase_Date BETWEEN DATE '2023-01-01' AND DATE '2025-12-31'
)
SELECT
    ProductName,
    Yr AS Year,
    CASE WHEN GROUPING(Mn) = 0 THEN Mn END AS Month,
    CASE WHEN GROUPING(Qr) = 0 THEN Qr END AS Quarter,
    CASE WHEN GROUPING(Hf) = 0 THEN Hf END AS HalfYear,
    SUM(TotalSeats) AS TotalLicenses,
    SUM(TotalSeats * UnitPrice) AS TotalCost
FROM src
GROUP BY GROUPING SETS (
    (ProductName, Yr, Mn),
    (ProductName, Yr, Qr),
    (ProductName, Yr, Hf),
    (ProductName, Yr)
)
ORDER BY Year, Month, Quarter, HalfYear;

-- Задание 4
-- Вычисление итогов стоимости ПО за период:
-- - количество и стоимость лицензий
-- - сравнение с общим количеством лицензий, %
-- - сравнение с общей стоимостью лицензий, %
-- Одним запросом, без процедуры

SELECT
    p.Category AS Category,
    p.Name AS Product,
    EXTRACT(YEAR FROM l.Purchase_Date) AS Yr,
    COUNT(*) AS Lic_Count,
    SUM(l.Unit_Price * l.Total_Seats) AS Total_Cost,
    CAST( COUNT(*) * 100 / SUM(COUNT(*)) OVER ()AS NUMBER(5,2)) AS Pct_Of_Count,
    CAST( SUM(l.Unit_Price * l.Total_Seats) * 100 /
        SUM(SUM(l.Unit_Price * l.Total_Seats)) OVER ()  AS NUMBER(5,2)
            ) AS Pct_Of_Cost

FROM Licenses l
JOIN Products p ON l.Product_ID = p.Product_ID
WHERE l.Purchase_Date BETWEEN DATE '2024-01-01' AND DATE '2026-12-31'
GROUP BY p.Category, p.Name, EXTRACT(YEAR FROM l.Purchase_Date)
ORDER BY p.Category, p.Name, Yr;

-- Задание 7
-- Для каждого вендора - суммы затрат
-- на лицензирование за последние 6 месяцев помесячно

SELECT
    v.Name AS "Вендор",
    EXTRACT(YEAR FROM l.Purchase_Date) AS "Год",
    EXTRACT(MONTH FROM l.Purchase_Date) AS "Месяц",
    SUM(l.Unit_Price * l.Total_Seats) AS "Стоимость за месяц",
    SUM(SUM(l.Unit_Price * l.Total_Seats)) OVER (
        PARTITION BY v.Vendor_ID
    ) AS "Итого за 6 месяцев по вендору"
FROM Licenses l
JOIN Products p
    ON l.Product_ID = p.Product_ID
JOIN Vendors v
    ON p.Vendor_ID = v.Vendor_ID
WHERE l.Purchase_Date >= ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -5)
  AND l.Purchase_Date <  ADD_MONTHS(TRUNC(SYSDATE, 'MM'), 1)
GROUP BY
    v.Vendor_ID,
    v.Name,
    EXTRACT(YEAR FROM l.Purchase_Date),
    EXTRACT(MONTH FROM l.Purchase_Date)
ORDER BY
    v.Name,
    "Год",
    "Месяц";

